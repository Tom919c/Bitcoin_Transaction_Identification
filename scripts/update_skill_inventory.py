"""Build a searchable inventory of locally installed agent skills."""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "SKILLS_INVENTORY.md"
USER_HOME = Path.home()

ROOTS = (
    ("Codex active", USER_HOME / ".codex" / "skills"),
    ("Codex active", USER_HOME / ".agents" / "skills"),
    ("Codex plugin", USER_HOME / ".codex" / "plugins" / "cache"),
    ("Other client mirror", USER_HOME / ".claude" / "skills"),
    ("Other client mirror", USER_HOME / ".continue" / "skills"),
    ("Other client mirror", USER_HOME / ".gemini" / "skills"),
    ("Other client mirror", USER_HOME / ".copilot" / "skills"),
    ("Repository local", REPO_ROOT / ".agents" / "skills"),
    ("Repository local", REPO_ROOT / ".codex" / "skills"),
)

FIELD_RE = re.compile(r"^(name|description):\s*(.*?)\s*$", re.MULTILINE)


@dataclass(frozen=True)
class Skill:
    name: str
    description: str
    scope: str
    path: Path


def _scalar(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        value = value[1:-1]
    return value.replace("\\\"", "\"").replace("\\'", "'")


def _metadata(path: Path) -> tuple[str, str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    frontmatter = (
        text.split("---", 2)[1]
        if text.startswith("---") and text.count("---") >= 2
        else text
    )
    fields = {match.group(1): _scalar(match.group(2)) for match in FIELD_RE.finditer(frontmatter)}
    name = fields.get("name") or path.parent.name
    description = fields.get("description", "")
    if description in {">", ">-", "|", "|-"}:
        lines = frontmatter.splitlines()
        start = next(
            (index for index, line in enumerate(lines) if line.startswith("description:")),
            -1,
        )
        parts: list[str] = []
        for line in lines[start + 1 :]:
            if line and not line[0].isspace():
                break
            if line.strip():
                parts.append(line.strip())
        description = " ".join(parts) or "See SKILL.md"
    return name, description


def _display_path(path: Path) -> str:
    try:
        return ".\\" + str(path.relative_to(REPO_ROOT))
    except ValueError:
        pass
    try:
        return "~\\" + str(path.relative_to(USER_HOME))
    except ValueError:
        return str(path)


def _cell(value: str) -> str:
    return " ".join(value.split()).replace("|", "\\|")


def discover() -> tuple[list[Skill], list[tuple[str, Path, int]]]:
    skills: list[Skill] = []
    root_counts: list[tuple[str, Path, int]] = []
    seen: set[Path] = set()
    for scope, root in ROOTS:
        manifests = (
            sorted(root.rglob("SKILL.md"), key=lambda path: str(path).casefold())
            if root.exists()
            else []
        )
        count = 0
        for path in manifests:
            resolved = path.resolve()
            if resolved in seen:
                continue
            seen.add(resolved)
            name, description = _metadata(path)
            skills.append(Skill(name, description, scope, path))
            count += 1
        root_counts.append((scope, root, count))
    skills.sort(key=lambda skill: (skill.name.casefold(), skill.scope, str(skill.path).casefold()))
    return skills, root_counts


def render() -> str:
    skills, root_counts = discover()
    unique_names = len({skill.name.casefold() for skill in skills})
    active_scopes = {"Codex active", "Codex plugin", "Repository local"}
    active_count = sum(1 for skill in skills if skill.scope in active_scopes)
    lines = [
        "# Skill Inventory",
        "",
        "> Generated by `python scripts/update_skill_inventory.py`. Do not edit by hand.",
        "",
        f"- Physical `SKILL.md` manifests: **{len(skills)}**",
        f"- Unique skill names: **{unique_names}**",
        f"- Codex-active/plugin/repository manifests: **{active_count}**",
        "- The runtime-provided skill list remains the authority for what is callable "
        "in a given turn; other-client copies are discovery mirrors.",
        "",
        "## Scanned roots",
        "",
        "| Scope | Root | Manifests |",
        "|---|---|---:|",
    ]
    lines.extend(
        f"| {_cell(scope)} | `{_display_path(root)}` | {count} |"
        for scope, root, count in root_counts
    )
    lines.extend(
        [
            "",
            "Search this file by task keyword, then open the selected `SKILL.md` "
            "completely before acting.",
        ]
    )
    for heading, selected in (
        (
            "Codex-side installed manifests",
            [skill for skill in skills if skill.scope != "Other client mirror"],
        ),
        (
            "Other-client discovery mirrors",
            [skill for skill in skills if skill.scope == "Other client mirror"],
        ),
    ):
        lines.extend(
            [
                "",
                f"## {heading}",
                "",
                "| Skill | Description | Scope | Manifest |",
                "|---|---|---|---|",
            ]
        )
        lines.extend(
            f"| `{_cell(skill.name)}` | {_cell(skill.description)} | {skill.scope} | "
            f"`{_display_path(skill.path)}` |"
            for skill in selected
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check", action="store_true", help="fail if the inventory is missing or stale"
    )
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"stale: {OUTPUT}")
            return 1
        print(f"current: {OUTPUT}")
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
